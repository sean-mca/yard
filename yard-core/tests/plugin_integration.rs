// ---- Provider trait test ----

#[tokio::test]
async fn test_plugin_provider_implements_provider_trait() {
    let binary = build_test_plugin();
    let config = PluginHostConfig {
        plugins_dir: PathBuf::from("/tmp/yard-test-plugins"),
        timeout_secs: 5,
        lock_file_path: None,
    };

    let provider = PluginProvider::from_binary(
        binary,
        "test-plugin".to_string(),
        config,
    );

    // Verify object safety -- store as Box<dyn Provider>
    let boxed: Box<dyn Provider> = Box::new(provider);

    // Call deploy through the Provider trait interface
    let result = boxed
        .deploy("test-job", "print('hello')", &json!({"type": "glue"}))
        .await;

    let resources = result.unwrap();
    assert_eq!(resources.len(), 1);
    assert_eq!(resources[0].r#type, "TestResource");
    assert_eq!(resources[0].id, "test-123");
}
