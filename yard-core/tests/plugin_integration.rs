// ---- Protocol tests ----

#[tokio::test]
async fn test_progress_lines_received_during_deploy() {
    let spawner = make_spawner(None);
    // Deploy operation emits a progress line. The spawner's typed methods
    // use eprintln for progress, but we can verify the operation succeeds
    // (which means the progress line was parsed and not treated as the
    // response). If progress parsing were broken, the response would be
    // the progress JSON and deserialization would fail.
    let result = spawner
        .call_deploy("test-job", "print('hello')", &json!({"type": "glue"}))
        .await;

    // Success implies the progress line was correctly parsed and skipped
    let resources = result.unwrap();
    assert_eq!(resources.len(), 1, "deploy should return one resource");
}

#[tokio::test]
async fn test_version_mismatch_rejected() {
    let spawner = make_spawner(Some("bad_version"));
    let result = spawner
        .call_validate("test-job", &json!({"type": "glue"}))
        .await;

    assert!(result.is_err(), "bad version should be rejected");
    let err_msg = format!("{:#}", result.unwrap_err());
    assert!(
        err_msg.contains("version") && err_msg.contains("mismatch"),
        "error should mention version mismatch, got: {err_msg}"
    );
}

