#[tokio::test]
async fn test_timeout_kills_hung_process() {
    let spawner = make_spawner_with_timeout(Some("hang"), 1);
    let result = spawner
        .call_validate("test-job", &json!({"type": "glue"}))
        .await;

    assert!(result.is_err(), "hung plugin should time out");
    let err_msg = format!("{:#}", result.unwrap_err());
    assert!(
        err_msg.contains("timed out"),
        "error should mention timeout, got: {err_msg}"
    );
}

